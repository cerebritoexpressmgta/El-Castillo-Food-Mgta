-- Ejecutar en Supabase > SQL Editor (una sola vez)

-- 0) Negocios (clientes). Una sola base de datos sirve a varios negocios.
create table if not exists public.negocios (
  id              int generated by default as identity primary key,
  slug            text not null unique,
  nombre          text not null,
  hosts           text[] not null default '{}',
  activo          boolean not null default true,
  max_sucursales  int not null default 1 check (max_sucursales >= 1),
  plan            text not null default 'basico',
  marca_original  boolean not null default false, -- true = conserva los archivos de marca originales (logo, íconos) tal cual
  ultimo_ping     timestamptz,
  creado_en       timestamptz not null default now()
);
create index if not exists negocios_hosts_gin on public.negocios using gin (hosts);
alter table public.negocios enable row level security;
revoke all on public.negocios from anon, authenticated;

-- 1) Estado de la aplicación (menú, pedidos, usuarios...): UNA fila por negocio (id = negocios.id)
create table if not exists public.app_state (
  id          int primary key references public.negocios (id) on delete cascade,
  version     bigint not null default 1,
  data        jsonb  not null,
  evento      jsonb,
  last_ping   timestamptz,
  updated_at  timestamptz not null default now()
);

-- Candado total: nadie con la llave pública (anon) puede leer ni escribir.
-- Solo el Worker, con la llave service_role (secreta), accede.
alter table public.app_state enable row level security;
revoke all on public.app_state from anon, authenticated;

-- 2) Imágenes del menú (bucket público de solo lectura)
insert into storage.buckets (id, name, public)
values ('imagenes', 'imagenes', true)
on conflict (id) do nothing;
