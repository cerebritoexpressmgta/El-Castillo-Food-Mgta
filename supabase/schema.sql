-- Ejecutar en Supabase > SQL Editor (una sola vez)

-- 0) Negocios (clientes). Una sola base de datos sirve a varios negocios.
create table if not exists public.negocios (
  id              int generated by default as identity primary key,
  slug            text not null unique,
  nombre          text not null,
  hosts           text[] not null default '{}',
  activo          boolean not null default true,
  max_sucursales  int not null default 1 check (max_sucursales >= 1),
  plan            text not null default 'basico',
  plantilla       text not null default 'general',
  precio_mensual  numeric(10,2) not null default 0 check (precio_mensual >= 0),
  moneda          text not null default 'USD',
  vence_el        date,
  dias_gracia     int not null default 5 check (dias_gracia >= 0),
  notas           text not null default '',
  marca_original  boolean not null default false, -- true = conserva los archivos de marca originales (logo, íconos) tal cual
  ultimo_ping     timestamptz,
  creado_en       timestamptz not null default now()
);
create index if not exists negocios_hosts_gin on public.negocios using gin (hosts);
alter table public.negocios enable row level security;
revoke all on public.negocios from anon, authenticated;

-- 1) Estado de la aplicación (menú, pedidos, usuarios...): UNA fila por negocio (id = negocios.id)
create table if not exists public.app_state (
  id          int primary key references public.negocios (id) on delete cascade,
  version     bigint not null default 1,
  data        jsonb  not null,
  evento      jsonb,
  last_ping   timestamptz,
  updated_at  timestamptz not null default now()
);

-- Candado total: nadie con la llave pública (anon) puede leer ni escribir.
-- Solo el Worker, con la llave service_role (secreta), accede.
alter table public.app_state enable row level security;
revoke all on public.app_state from anon, authenticated;

-- 2) Imágenes del menú (bucket público de solo lectura)
insert into storage.buckets (id, name, public)
values ('imagenes', 'imagenes', true)
on conflict (id) do nothing;

-- Pagos de suscripción de cada negocio
create table if not exists public.negocio_pagos (
  id bigint generated always as identity primary key,
  negocio_id int not null references public.negocios (id) on delete cascade,
  fecha date not null default current_date, monto numeric(10,2) not null check (monto >= 0),
  moneda text not null default 'USD', metodo text not null default '', referencia text not null default '',
  meses int not null default 1 check (meses between 1 and 24), vence_el_nuevo date, notas text not null default '',
  creado_en timestamptz not null default now()
);
create index if not exists negocio_pagos_negocio on public.negocio_pagos (negocio_id, fecha desc);
alter table public.negocio_pagos enable row level security;
revoke all on public.negocio_pagos from anon, authenticated;
