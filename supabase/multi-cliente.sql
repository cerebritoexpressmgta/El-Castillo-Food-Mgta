-- 1) Tabla de negocios (clientes)
create table if not exists public.negocios (
  id              int generated by default as identity primary key,
  slug            text not null unique,
  nombre          text not null,
  hosts           text[] not null default '{}',   -- dominios que atienden a este negocio
  activo          boolean not null default true,  -- false = suspendido (impago, baja...)
  max_sucursales  int not null default 1 check (max_sucursales >= 1),
  plan            text not null default 'basico',
  marca_original  boolean not null default false, -- true = conserva los archivos de marca originales (logo, íconos) tal cual
  ultimo_ping     timestamptz,
  creado_en       timestamptz not null default now()
);
create index if not exists negocios_hosts_gin on public.negocios using gin (hosts);

-- 2) El negocio actual pasa a ser el n.º 1
insert into public.negocios (id, slug, nombre, hosts, max_sucursales, marca_original)
overriding system value
values (1, 'el-castillo', 'El Castillo Food Mgta', array['TU-DOMINIO.com'], 1, true)
on conflict (id) do nothing;

-- La siguiente identidad empieza después del id más alto
select setval(pg_get_serial_sequence('public.negocios', 'id'), greatest((select max(id) from public.negocios), 1));

-- 3) Cada fila de app_state pertenece a un negocio (borrar el negocio borra sus datos)
alter table public.app_state drop constraint if exists app_state_negocio_fk;
alter table public.app_state
  add constraint app_state_negocio_fk foreign key (id) references public.negocios (id) on delete cascade;

-- 4) Candado: solo el Worker (llave service_role) accede, igual que app_state
alter table public.negocios enable row level security;
revoke all on public.negocios from anon, authenticated;
